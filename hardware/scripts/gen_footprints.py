"""Write the project footprint library hardware/PixelPine.pretty (+ fp-lib-table).

- LED_0603_Dense : stock LED_0603_1608Metric without silkscreen, courtyard = pads + 0.12 mm,
                   hidden reference -> lets 240 LEDs sit on a 2 mm grid and pass DRC.
- TouchStar      : capacitive touch pad in the shape of the tree-top star (from geometry.py).
- USB_C_SHOUHAN_TYPE-C-6P : the real C456012 receptacle, pads copied from LCSC's EasyEDA footprint.
Also writes PixelPine.kicad_sym (PY32F003F18P6 symbol).
Run before gen_sch.py / gen_pcb.py.
"""
import math
import os
import re

import geometry as g
import kicad_lib as kl

HERE = os.path.dirname(os.path.abspath(__file__))
HW = os.path.normpath(os.path.join(HERE, ".."))
LIB = os.path.join(HW, "PixelPine.pretty")
STOCK_LED = os.path.join(kl.KICAD_SHARE, "footprints", "LED_SMD.pretty", "LED_0603_1608Metric.kicad_mod")
STAR_INSET = 0.55   # copper pullback from the board edge


def _drop_blocks(s, head, predicate):
    """Remove every s-expression starting with `head` for which predicate(block_text) is True."""
    out, i = [], 0
    for m in re.finditer(re.escape(head), s):
        if m.start() < i:
            continue
        j = kl._balanced(s, m.start())
        if predicate(s[m.start():j]):
            out.append(s[i:m.start()])
            i = j
    out.append(s[i:])
    return "".join(out)


def led_dense():
    s = open(STOCK_LED, encoding="utf8").read()
    s = s.replace('(footprint "LED_0603_1608Metric"', '(footprint "LED_0603_Dense"', 1)
    s = re.sub(r'\(descr "[^"]*"\)', '(descr "0603 LED for the dense 45-degree PixelPine grid: no silk, '
               'courtyard = pads + 0.12 mm. Derived from LED_SMD:LED_0603_1608Metric")', s, count=1)
    s = _drop_blocks(s, "(fp_line", lambda b: '"F.SilkS"' in b)
    s = _drop_blocks(s, "(fp_rect", lambda b: '"F.CrtYd"' in b)
    # hide the silkscreen reference
    s = re.sub(r'(\(property "Reference" "REF\*\*"\s*\(at [^)]*\)\s*\(layer "F.SilkS"\))',
               r"\1 (hide yes)", s, count=1)
    crt = ('\t(fp_rect (start -1.345 -0.595) (end 1.345 0.595) (stroke (width 0.05) (type solid)) '
           '(fill no) (layer "F.CrtYd"))\n')
    s = s.replace("\t(pad ", crt + "\t(pad ", 1)
    return s


def touch_star():
    """Puffy star inset from the outline, shrunk uniformly until every pad edge point keeps
    >= 0.52 mm from the board edge (the neck below the star is the tight spot)."""
    cx, cy = g.STAR_C
    outline = g.outline_polygon()
    scale = 1.0
    for _ in range(100):
        loc = [(x - cx, y - cy) for x, y in g.star_points(72, (g.STAR_R - STAR_INSET) * scale,
                                                         (g.STAR_r - STAR_INSET) * scale)]
        worst = min(g.dist_to_poly_edge((x + cx, y + cy), outline) for x, y in loc)
        if worst >= 0.52:
            break
        scale *= 0.98
    pts = [f"(xy {x:.4f} {y:.4f})" for x, y in loc]
    return f"""(footprint "TouchStar"
\t(version 20241229)
\t(generator "pixelpine_gen")
\t(layer "F.Cu")
\t(descr "Capacitive touch electrode shaped as the tree-top star, exposed on BOTH faces and joined by a plated hole, so a front+back pinch reads as a squeeze. Generated by gen_footprints.py")
\t(property "Reference" "TP" (at 0 -5.5 0) (layer "F.SilkS") (hide yes) (effects (font (size 0.8 0.8) (thickness 0.12))))
\t(property "Value" "STAR" (at 0 5.5 0) (layer "F.Fab") (effects (font (size 0.8 0.8) (thickness 0.12))))
\t(attr through_hole exclude_from_pos_files exclude_from_bom)
\t(pad "1" thru_hole custom (at 0 0) (size 1.3 1.3) (drill 0.6) (layers "*.Cu" "*.Mask")
\t\t(options (clearance outline) (anchor circle))
\t\t(primitives (gr_poly (pts {" ".join(pts)}) (width 0) (fill yes)))
\t)
)
"""


# SHOU HAN TYPE-C 6P (LCSC C456012), copied from LCSC's own EasyEDA footprint "TYPE-C-SMD_TYPE-C-6P_1"
# (easyeda.com/api/products/C456012/components), converted from 10 mil units. The origin is kept where LCSC has it,
# so JLC's CPL needs no offset. Mouth at +y. 6 SMD pads + 4 plated shell slots (paste-in-hole, reflowed with the
# rest of the board, no hand soldering).
USB_PADS = [("B12", -2.70, 0.8), ("B9", -1.50, 0.7), ("A5", -0.50, 0.7), ("B5", 0.50, 0.7), ("A9", 1.50, 0.7),
            ("A12", 2.70, 0.8)]                         # (number, x, width); all at y -2.025, 1.2 mm long
USB_PAD_Y = -2.025
USB_SHELL = [(-4.32, -1.775), (-4.32, 2.025), (4.32, -1.775), (4.32, 2.025)]   # 1.1 x 1.9 pad, 0.6 x 1.3 slot
USB_BODY = (-4.47, -2.124, 4.47, 4.626)                  # x0 y0 x1 y1; y1 = mouth face
USB_MODEL_DY = 1.25                                       # stand-in 3D model (GCT USB4125) is body-centred


def usb_c_6p():
    x0, y0, x1, y1 = USB_BODY
    pads = "".join(
        f'\t(pad "{n}" smd roundrect (at {x:.3f} {USB_PAD_Y}) (size {w} 1.2) (layers "F.Cu" "F.Mask" "F.Paste") '
        f'(roundrect_rratio 0.25))\n' for n, x, w in USB_PADS)
    pads += "".join(
        f'\t(pad "SH" thru_hole oval (at {x} {y}) (size 1.1 1.9) (drill oval 0.6 1.3) '
        f'(layers "*.Cu" "*.Mask" "F.Paste") (remove_unused_layers no))\n' for x, y in USB_SHELL)
    silk = "".join(f'\t(fp_line (start {sx} -0.6) (end {sx} 0.85) (stroke (width 0.12) (type solid)) (layer "F.SilkS"))\n'
                   for sx in (-4.67, 4.67))
    return f"""(footprint "USB_C_SHOUHAN_TYPE-C-6P"
\t(version 20241229)
\t(generator "pixelpine_gen")
\t(layer "F.Cu")
\t(descr "USB Type-C receptacle, power only, 6P, top mount, SHOU HAN TYPE-C 6P, LCSC C456012. Pads from LCSC's EasyEDA footprint TYPE-C-SMD_TYPE-C-6P_1, same origin. Generated by gen_footprints.py")
\t(tags "USB C Type-C receptacle power-only 6P C456012")
\t(property "Reference" "REF**" (at 0 -3.6 0) (layer "F.SilkS") (effects (font (size 1 1) (thickness 0.15))))
\t(property "Value" "TYPE-C 6P" (at 0 5.8 0) (layer "F.Fab") (effects (font (size 1 1) (thickness 0.15))))
\t(attr smd)
\t(fp_rect (start {x0} {y0}) (end {x1} {y1}) (stroke (width 0.1) (type solid)) (fill no) (layer "F.Fab"))
\t(fp_rect (start -5.2 -2.9) (end 5.2 5.1) (stroke (width 0.05) (type solid)) (fill no) (layer "F.CrtYd"))
\t(fp_line (start -5 {y1}) (end 5 {y1}) (stroke (width 0.1) (type solid)) (layer "Dwgs.User"))
\t(fp_text user "mouth / PCB edge" (at 0 {y1 - 0.5} 0) (layer "Dwgs.User") (effects (font (size 0.5 0.5) (thickness 0.1))))
{silk}{pads}\t(model "${{KICAD10_3DMODEL_DIR}}/Connector_USB.3dshapes/USB_C_Receptacle_GCT_USB4125-xx-x_6P_TopMnt_Horizontal.step"
\t\t(offset (xyz 0 {-USB_MODEL_DY} 0)) (scale (xyz 1 1 1)) (rotate (xyz 0 0 0)))
)
"""


# PY32F003F18P6, TSSOP-20 "Pinout 1" (datasheet Rev 1.7, figure 3-3: PY32F003F1xPx). KiCad ships no PY32F003 symbol,
# and the F002A symbol has a different pinout. (name, number, type, side, row) - rows count down from the top.
PY32_PINS = [
    ("PA0", 19, "bidirectional", "L", 0), ("PA1", 20, "bidirectional", "L", 1), ("PA2", 1, "bidirectional", "L", 2),
    ("PA3", 2, "bidirectional", "L", 3), ("PA4", 3, "bidirectional", "L", 4), ("PA5", 4, "bidirectional", "L", 5),
    ("PA6", 5, "bidirectional", "L", 6), ("PA7", 6, "bidirectional", "L", 7), ("PA12", 8, "bidirectional", "L", 8),
    ("PA13/SWDIO", 10, "bidirectional", "R", 0),                          # SWD pins top + bottom: room for pads
    ("PB5", 12, "bidirectional", "R", 1), ("PB6", 13, "bidirectional", "R", 2), ("PB7", 14, "bidirectional", "R", 3),
    ("PF0", 16, "bidirectional", "R", 4), ("PF1", 17, "bidirectional", "R", 5), ("PF4/BOOT0", 15, "bidirectional", "R", 6),
    ("PF2/NRST", 18, "bidirectional", "R", 7), ("PA14/SWCLK", 11, "bidirectional", "R", 8),
    ("VCC", 9, "power_in", "T", 0), ("VSS", 7, "power_in", "B", 0),
]


def py32_symbol():
    f = '(effects (font (size 1.27 1.27)))'
    fh = '(hide yes) (effects (font (size 1.27 1.27)))'
    pins = []
    for name, num, typ, side, row in PY32_PINS:
        if side in "LR":
            x, y, ang = (-12.7, 10.16 - row * 2.54, 0) if side == "L" else (12.7, 10.16 - row * 2.54, 180)
        else:
            x, y, ang = (0, 17.78, 270) if side == "T" else (0, -17.78, 90)
        pins.append(f'(pin {typ} line (at {x} {y} {ang}) (length 2.54) (name "{name}" {f}) (number "{num}" {f}))')
    return f"""(kicad_symbol_lib
\t(version 20251024)
\t(generator "pixelpine_gen")
\t(generator_version "10.0")
\t(symbol "PY32F003F18P6"
\t\t(exclude_from_sim no) (in_bom yes) (on_board yes)
\t\t(property "Reference" "U" (at 2.54 19.05 0) (effects (font (size 1.27 1.27)) (justify left)))
\t\t(property "Value" "PY32F003F18P6" (at 2.54 -19.05 0) (effects (font (size 1.27 1.27)) (justify left)))
\t\t(property "Footprint" "Package_SO:TSSOP-20_4.4x6.5mm_P0.65mm" (at 0 0 0) {fh})
\t\t(property "Datasheet" "https://download.py32.org/Datasheet/en/PY32F003_Datasheet_Rev1.7.pdf" (at 0 0 0) {fh})
\t\t(property "Description" "Puya ARM Cortex-M0+ 32 MHz, 64 KB flash, 8 KB SRAM, TSSOP-20 pinout 1 (F1xPx). Generated by gen_footprints.py" (at 0 0 0) {fh})
\t\t(symbol "PY32F003F18P6_0_1"
\t\t\t(rectangle (start -10.16 15.24) (end 10.16 -15.24) (stroke (width 0.254) (type default)) (fill (type background)))
\t\t)
\t\t(symbol "PY32F003F18P6_1_1"
\t\t\t{chr(10).join(pins)}
\t\t)
\t\t(embedded_fonts no)
\t)
)
"""


def main():
    os.makedirs(LIB, exist_ok=True)
    for name, body in (("LED_0603_Dense", led_dense()), ("TouchStar", touch_star()),
                       ("USB_C_SHOUHAN_TYPE-C-6P", usb_c_6p())):
        with open(os.path.join(LIB, name + ".kicad_mod"), "w", encoding="utf8", newline="\n") as f:
            f.write(body)
    with open(os.path.join(HW, "PixelPine.kicad_sym"), "w", encoding="utf8", newline="\n") as f:
        f.write(py32_symbol())
    with open(os.path.join(HW, "fp-lib-table"), "w", newline="\n") as f:
        f.write('(fp_lib_table\n  (version 7)\n  (lib (name "PixelPine")(type "KiCad")'
                '(uri "${KIPRJMOD}/PixelPine.pretty")(options "")(descr "PixelPine project footprints"))\n)\n')
    with open(os.path.join(HW, "sym-lib-table"), "w", newline="\n") as f:
        f.write('(sym_lib_table\n  (version 7)\n  (lib (name "PixelPine")(type "KiCad")'
                '(uri "${KIPRJMOD}/PixelPine.kicad_sym")(options "")(descr "PixelPine project symbols"))\n)\n')
    print("wrote", LIB, "and PixelPine.kicad_sym")


if __name__ == "__main__":
    main()
