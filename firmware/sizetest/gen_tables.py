"""Generate tables.c: every per-LED constant the firmware needs, precomputed on the PC.

No trigonometry or floating point ever runs on the MCU (neither the PY32F003 nor the CH32V003 has an FPU);
it all ends up here as const byte tables in flash. Input: hardware/led_map.json (from geometry.py).
"""
import json
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
M = json.load(open(os.path.join(HERE, "..", "..", "hardware", "led_map.json")))
L = M["leds"]
N = len(L)
SX, SY = M["star_c"]
Y0 = min(l["y"] for l in L)
Y1 = max(l["y"] for l in L)
GXMIN = min(l["gx"] for l in L)
GYMIN = min(l["gy"] for l in L)
GW = max(l["gx"] for l in L) - GXMIN + 1
GH = max(l["gy"] for l in L) - GYMIN + 1

row_half = {}
for l in L:
    row_half[l["gy"]] = max(row_half.get(l["gy"], 0), abs(l["x"]) + M["pitch"] / 2)


def c_array(ctype, name, vals, per_line=24):
    body = ",".join(str(int(v)) for v in vals)
    lines = []
    parts = body.split(",")
    for i in range(0, len(parts), per_line):
        lines.append("  " + ",".join(parts[i:i + per_line]) + ",")
    return f"const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


def clamp(v, a, b):
    return max(a, min(b, v))


out = ['/* Generated by gen_tables.py from hardware/led_map.json - do not edit */', '#include "pp.h"', ""]
out.append(c_array("int8_t", "led_x4", [clamp(round(l["x"] * 4), -127, 127) for l in L]))           # x in 0.25 mm
out.append(c_array("uint8_t", "led_y4", [clamp(round(l["y"] * 4), 0, 255) for l in L]))            # y in 0.25 mm
out.append(c_array("uint8_t", "led_ds4", [clamp(round(math.hypot(l["x"] - SX, l["y"] - SY) * 4), 0, 255) for l in L]))
out.append(c_array("uint8_t", "led_ang", [round(math.atan2(l["y"] - SY, l["x"] - SX) / (2 * math.pi) * 256) & 255 for l in L]))
out.append(c_array("int8_t", "led_th", [round(math.asin(clamp(l["x"] / row_half[l["gy"]], -0.999, 0.999)) / (math.pi / 2) * 64) for l in L]))
grid = [255] * (GW * GH)
for i, l in enumerate(L):
    grid[(l["gy"] - GYMIN) * GW + (l["gx"] - GXMIN)] = i
out.append(c_array("uint8_t", "grid", grid))
col_bottom = [-1] * GW
for l in L:
    col_bottom[l["gx"] - GXMIN] = max(col_bottom[l["gx"] - GXMIN], l["gy"])
out.append(c_array("int8_t", "col_bottom", col_bottom))
out.append(c_array("uint8_t", "row_half4", [round(row_half.get(g, 4) * 4) for g in range(GYMIN, GYMIN + GH)]))
# shared maths LUTs
out.append(c_array("int8_t", "sin8_lut", [round(math.sin(i / 256 * 2 * math.pi) * 127) for i in range(256)]))
out.append(c_array("uint8_t", "gauss_lut", [round(math.exp(-(i / 16) ** 2) * 255) for i in range(64)]))
rnd = random.Random(42)
perm = list(range(256))
rnd.shuffle(perm)
out.append(c_array("uint8_t", "perm", perm))
# charlieplex map: the 15 LEDs of every anode phase and their cathode lines (the arrangement is in hardware/led_assignment.json)
by_anode = [[(i, l["c"]) for i, l in enumerate(L) if l["a"] == a] for a in range(16)]
assert all(len(ph) == 15 for ph in by_anode), "every anode line must drive exactly 15 LEDs"
out.append(c_array("uint8_t", "phase_led", [i for ph in by_anode for i, _ in ph]))
out.append(c_array("uint8_t", "phase_cath", [c for ph in by_anode for _, c in ph]))

with open(os.path.join(HERE, "tables.c"), "w", newline="\n") as f:
    f.write("\n".join(out))
with open(os.path.join(HERE, "geom.h"), "w", newline="\n") as f:
    f.write(f"""/* Generated by gen_tables.py - do not edit */
#pragma once
#define NLED {N}
#define GXMIN ({GXMIN})
#define GYMIN {GYMIN}
#define GW {GW}
#define GH {GH}
#define STAR_X4 {round(SX * 4)}
#define STAR_Y4 {round(SY * 4)}
#define LED_Y0_4 {round(Y0 * 4)}
#define LED_Y1_4 {round(Y1 * 4)}
#define PITCH4 {round(M['pitch'] * 4)}
""")
print(f"tables.c: {N} LEDs, grid {GW}x{GH}")
